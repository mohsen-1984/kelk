    const i18n = {
        lang: 'fa',

        /** t('loaded', name) → string with {0} … filled */
        t: function (key) {
            const table = STRINGS[this.lang] || STRINGS.fa;
            let s = table[key] != null ? table[key] : (STRINGS.en[key] != null ? STRINGS.en[key] : key);
            for (let i = 1; i < arguments.length; i++) s = s.split('{' + (i - 1) + '}').join(arguments[i]);
            return s;
        },

        dir: function () { return this.lang === 'en' ? 'ltr' : 'rtl'; },

        /** The interface languages, each named in its own language (the switch shows the other ones). */
        languages: { fa: 'فارسی', en: 'English', ar: 'العربية' },

        /** Set the language and re-label the page. */
        apply: function (lang) {
            this.lang = STRINGS[lang] ? lang : 'fa';
            const root = document.documentElement;
            root.lang = this.lang;
            root.dir = this.dir();
            const self = this;
            document.querySelectorAll('[data-i18n]').forEach(function (el) {
                el.textContent = self.t(el.getAttribute('data-i18n'));
            });
            document.querySelectorAll('[data-i18n-attr]').forEach(function (el) {
                el.getAttribute('data-i18n-attr').split(';').forEach(function (pair) {
                    const kv = pair.split(':');
                    if (kv.length === 2) el.setAttribute(kv[0].trim(), self.t(kv[1].trim()));
                });
            });
            document.title = this.t('appName') + ' — ' + this.t('tagline');
        }
    };

    K.i18n = i18n;
