    const i18n = {
        lang: 'fa',

        /** t('loaded', name) → string with {0} … filled */
        t: function (key) {
            const table = STRINGS[this.lang] || STRINGS.fa;
            let s = table[key] != null ? table[key] : (STRINGS.en[key] != null ? STRINGS.en[key] : key);
            for (let i = 1; i < arguments.length; i++) s = s.split('{' + (i - 1) + '}').join(arguments[i]);
            return s;
        },

        dir: function () { return this.lang === 'en' ? 'ltr' : 'rtl'; },

        /**
         * Label the elements under root (data-i18n, data-i18n-attr). A key no table has yet is left alone: its words
         * come with a module loaded on demand (Settings → Excel: scripts/sheets.js), which labels its part then.
         */
        relabel: function (root) {
            const self = this;
            const has = function (k) { return STRINGS.en[k] != null; };
            root.querySelectorAll('[data-i18n]').forEach(function (el) {
                const k = el.getAttribute('data-i18n');
                if (has(k)) el.textContent = self.t(k);
            });
            root.querySelectorAll('[data-i18n-attr]').forEach(function (el) {
                el.getAttribute('data-i18n-attr').split(';').forEach(function (pair) {
                    const kv = pair.split(':');
                    if (kv.length === 2 && has(kv[1].trim())) el.setAttribute(kv[0].trim(), self.t(kv[1].trim()));
                });
            });
        },

        /**
         * The locale of {date} in an export's header/footer: an LTR header gets English, an RTL one the
         * interface's right-to-left language (Arabic in the Arabic interface, else Persian) — the same rule
         * as the page / of / contents words (Kelk.names.rtlWords). Latin digits, as before.
         */
        dateLocale: function (dir) {
            if (dir === 'ltr') return 'en-GB';
            return this.lang === 'ar' ? 'ar-u-nu-latn' : 'fa-IR-u-nu-latn';
        },

        /** The string tables, read by tools/check-i18n.js and the unit tests (not by the page). */
        _strings: STRINGS,

        /** The interface languages, each named in its own language (the switch shows the other ones). */
        languages: { fa: 'فارسی', en: 'English', ar: 'العربية' },

        /** Set the language and re-label the page. */
        apply: function (lang) {
            this.lang = typeof lang === 'string' && Object.prototype.hasOwnProperty.call(STRINGS, lang) ? lang : 'fa';   // not 'toString'
            const root = document.documentElement;
            root.lang = this.lang;
            root.dir = this.dir();
            this.relabel(document);
            document.title = (this.t('appName') + ' – ' + this.t('tagline')).replace(/ — /g, ' – ');   // en dashes: less room in a tab
        }
    };

    K.i18n = i18n;
