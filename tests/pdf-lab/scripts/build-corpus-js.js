// tests/pdf-lab/corpus.js from tests/pdf-lab/corpus/*.md: the corpus as a script, so tests/pdf-import-suite.html scores
// the PDFs you pick offline, from file:// (a page there cannot fetch the .md files). Run after a corpus document changes:
//   node tests/pdf-lab/scripts/build-corpus-js.js
const fs = require('fs'), path = require('path');
const LAB = path.join(__dirname, '..'), dir = path.join(LAB, 'corpus');
const docs = {};
fs.readdirSync(dir).filter((f) => /\.md$/.test(f)).sort().forEach((f) => { docs[f.replace(/\.md$/, '')] = fs.readFileSync(path.join(dir, f), 'utf8'); });
const js = '/**\n * The PDF lab\'s corpus (tests/pdf-lab/corpus/*.md) for tests/pdf-import-suite.html — generated by\n' +
  ' * tests/pdf-lab/scripts/build-corpus-js.js; do not edit by hand.\n */\nwindow.KELK_PDF_CORPUS = ' + JSON.stringify(docs, null, 1) + ';\n';
fs.writeFileSync(path.join(LAB, 'corpus.js'), js);
console.log('tests/pdf-lab/corpus.js:', Object.keys(docs).length, 'documents,', Buffer.byteLength(js), 'bytes');
