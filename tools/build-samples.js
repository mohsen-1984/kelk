/**
 * Build the sample scripts the page loads (a <script> tag works from file://, fetch does not):
 *   docs/about-kelk-and-samples.js  ← docs/about-kelk-and-samples.<lang>.md  (KelkSamples)
 *   docs/slides-samples.js          ← docs/slides-sample.<lang>.md           (KelkSlideSamples: the Slides view)
 * Run with Node after editing a sample:  node tools/build-samples.js
 * A new language is a new file (about-kelk-and-samples.ar.md → KelkSamples.ar).
 */
const fs = require('fs'), path = require('path');
const dir = path.join(__dirname, '..', 'docs');
const samples = {};
// sorted: readdir order is the file system's (alphabetical on NTFS, hash order on Linux ext4), and the key order
// is written into the file, so an unsorted list made the output depend on the machine (CI's freshness check)
fs.readdirSync(dir).sort().forEach(function (f) {
    const m = /^about-kelk-and-samples\.([a-z]{2,3})\.md$/.exec(f);
    if (m) samples[m[1]] = { name: f, markdown: fs.readFileSync(path.join(dir, f), 'utf8') };
});
const js = '/**\n * Kelk: about + guide + samples, one document per interface language — generated by\n' +
    ' * tools/build-samples.js from docs/about-kelk-and-samples.<lang>.md; do not edit by hand.\n */\n' +
    'window.KelkSamples = ' + JSON.stringify(samples, null, 1) + ';\n';
fs.writeFileSync(path.join(dir, 'about-kelk-and-samples.js'), js);
console.log('docs/about-kelk-and-samples.js:', Object.keys(samples).join(', '), Buffer.byteLength(js), 'bytes');

const slides = {};
fs.readdirSync(dir).forEach(function (f) {
    const m = /^slides-sample\.([a-z]{2,3})\.md$/.exec(f);
    if (m) slides[m[1]] = { name: f, markdown: fs.readFileSync(path.join(dir, f), 'utf8') };
});
const js2 = '/**\n * Kelk: the slides sample (the Slides view), one deck per interface language — generated by\n' +
    ' * tools/build-samples.js from docs/slides-sample.<lang>.md; do not edit by hand.\n */\n' +
    'window.KelkSlideSamples = ' + JSON.stringify(slides, null, 1) + ';\n';
fs.writeFileSync(path.join(dir, 'slides-samples.js'), js2);
console.log('docs/slides-samples.js:', Object.keys(slides).join(', '), Buffer.byteLength(js2), 'bytes');
