/**
 * Build lib/pdfimport/letterstats.js — the letter pairs of our own text, by language, for the PDF importer's judge
 * (lib/pdfimport/trust.js): a font whose text is made of pairs no language of ours writes is not read right.
 *   node tools/build-letterstats.js          (`npm run check:fresh` runs it)
 * Sources: the lab's expected Markdown (tests/pdf-lab/corpus/*.md — «-fa», «-ar» in a name is its language, else en),
 * the READMEs and docs/*.md by their language suffix. Per language: every pair of adjacent letters inside a word, seen
 * twice or more — Arabic-script words for fa and ar (letters folded as the importer folds them: forms to letters,
 * ي ك to ی ک, marks and the tatweel dropped), Latin words (a–z, case folded) for en whatever the file's language.
 * Left out: the lab's files in fonts Kelk does not know (MEASURED). Their text is what the approximate reading (3.2)
 * must find and its accuracy is measured on: in the stats, the answer would help pick the letters and flatter the score.
 * 3.3's font files (tests/pdf-lab/scripts/make-cff33.py: the CFF programs, Word's ت, the tatweel ToUnicode) are left out
 * the same way, for good (the owner's decision, 2026-11-21).
 */
'use strict';
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const OUT = path.join(root, 'lib', 'pdfimport', 'letterstats.js');
const AR = /[\u0621-\u063A\u0641-\u064A\u067E\u0686\u0698\u06A9\u06AF\u06CC]/;
const fold = (s) => s.normalize('NFKC').replace(/[\u064B-\u065F\u0670\u0640]/g, '').replace(/[\u064A\u0649]/g, '\u06CC').replace(/\u0643/g, '\u06A9');

const MEASURED = ['glyph-index-fa.md', 'renumbered-en.md', 'unknown-serif-fa.md', 'unknown-serif-en.md', 'unreadable-fa.md',
  'cff-cid-fa.md', 'cff-type1c-fa.md', 'cff-known-fa.md', 'cff-unreadable-fa.md', 'cff-zwnj-fa.md', 'teh-fa.md', 'tatweel-fa.md',
  'scan-plain-fa.md', 'scan-framed-fa.md', 'scan-low-fa.md', 'scan-headings-fa.md', 'scan-columns-fa.md'];
const files = [];
const take = (dir, re, lang) => fs.readdirSync(path.join(root, dir)).filter((f) => re.test(f) && !(dir === 'tests/pdf-lab/corpus' && MEASURED.indexOf(f) >= 0)).sort().forEach((f) => files.push([path.join(root, dir, f), lang(f)]));
const byName = (f) => /[-.]fa\.md$/.test(f) ? 'fa' : /[-.]ar\.md$/.test(f) ? 'ar' : 'en';
take('tests/pdf-lab/corpus', /\.md$/, byName);
take('docs', /\.md$/, byName);
take('.', /^README(\.[a-z]+)?\.md$/, byName);

const count = { fa: {}, ar: {}, en: {} };
const add = (lang, word) => { for (let k = 0; k + 1 < word.length; k++) { const p = word[k] + word[k + 1]; count[lang][p] = (count[lang][p] || 0) + 1; } };
files.forEach(([file, lang]) => {
  const text = fold(fs.readFileSync(file, 'utf8').replace(/```[\s\S]*?```/g, ' ').replace(/\]\([^)]*\)/g, '] ').replace(/https?:\/\/\S+/g, ' '));
  text.split(/[^A-Za-z\u0621-\u063A\u0641-\u064A\u067E\u0686\u0698\u06A9\u06AF\u06CC\u200C]+/).forEach((w) => {
    w.split('\u200C').forEach((part) => {
      if (part.length < 2) return;
      if (AR.test(part[0])) { if (lang !== 'en' && Array.from(part).every((c) => AR.test(c))) add(lang, part); }
      else if (/^[A-Za-z]+$/.test(part)) add('en', part.toLowerCase());
    });
  });
});
const pairs = (lang) => Object.keys(count[lang]).filter((p) => count[lang][p] >= 2).sort().join('');
const text = '/**\n * Kelk — letter pairs of our own text by language (lib/pdfimport/letterstats.js): generated by\n' +
  ' * tools/build-letterstats.js; do not edit by hand. Each string: the pairs of adjacent letters seen inside words, two\n' +
  ' * characters a pair. Read by lib/pdfimport/trust.js (the judge). Load after lib/PdfImporter.js.\n */\n' +
  '(function (global) {\n    const PdfImporter = global.PdfImporter || (typeof require === \'function\' ? require(\'../PdfImporter.js\') : null);\n' +
  '    PdfImporter._letterstats = {\n' + ['fa', 'ar', 'en'].map((l) => '        ' + l + ': ' + JSON.stringify(pairs(l))).join(',\n') + '\n    };\n' +
  '})(typeof window !== \'undefined\' ? window : globalThis);\n';
fs.writeFileSync(OUT, text);
console.log('lib/pdfimport/letterstats.js:', ['fa', 'ar', 'en'].map((l) => l + ' ' + pairs(l).length / 2 + ' pairs').join(', ') + ',', Buffer.byteLength(text), 'bytes,', files.length, 'files');
