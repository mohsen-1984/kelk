#!/usr/bin/env node
/**
 * The Persian language model: tools/lm/lm.json and its file:// copy lib/pdfimport/lm-fa.js (Kelk 3.4).
 *
 * Counts only — letter unigrams, bigrams and trigrams (inside words, «^^» a word's start, «$» its end) and the words
 * seen at least MIN_WORD times, with their counts. OCR's post-correction (3.4) asks it whether a word is known; the
 * decipherment of fonts Kelk does not know (3.5) will score letter sequences with it. Loaded only when needed, never
 * at startup.
 *
 * Built from two kinds of text, after the same normalisation (NFKC; ي ى → ی, ك → ک; no harakat; ؤ → و, إ أ → ا):
 *   - tools/lm/kelk-text.txt — 80 % of the Persian text in the Kelk repository (2026-11-21, the font-recovery spike),
 *     counted KELK_WEIGHT times. Frozen: the lab files written since, the OCR lab's scans among them, are not in it;
 *     and the lines of the lab's answer texts it held (the files in build-letterstats.js's MEASURED: 38 lines, from
 *     3.2's glyph-index-fa, unknown-serif-fa and unreadable-fa) were taken out on 2026-11-21, their counts with them,
 *     so no reading is scored on text the model has seen;
 *   - the Leipzig Corpora Collection's Iranian Persian corpora (CC BY; credit in THIRD-PARTY-NOTICES.md):
 *     pes-ir_web-public_2019_100K and pes_wikipedia_2021_100K, downloaded from
 *     https://wortschatz.uni-leipzig.de/en/download/pes — never in the repository. Every HOLD-th web-public sentence is
 *     left out (the spike's OCR test text).
 *
 *   LM_SOURCES=<web-public sentences.txt>,<wikipedia sentences.txt> node tools/build-lm.js   → both files
 *   node tools/build-lm.js --js                                                              → lm-fa.js from lm.json
 *
 * tools/lm/lm.json was built with the defaults below (KELK_WEIGHT 30, MIN_WORD 10, HOLD 33). `npm run check:fresh`
 * runs the --js step only: the corpora are not in the repository.
 */
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const JSON_OUT = path.join(root, 'tools', 'lm', 'lm.json');
const JS_OUT = path.join(root, 'lib', 'pdfimport', 'lm-fa.js');
const KELK_WEIGHT = +(process.env.KELK_WEIGHT || 30), MIN_WORD = +(process.env.MIN_WORD || 10), HOLD = +(process.env.HOLD || 33);

const norm = (s) => s.normalize('NFKC').replace(/[يى]/g, 'ی').replace(/ك/g, 'ک').replace(/[ًٌٍَُِّْ]/g, '').replace(/[ؤ]/g, 'و').replace(/[إأ]/g, 'ا');
/** letter n-gram and word counts from raw text (several texts may be added in turn) */
function count(text, acc) {
  acc = acc || { c1: new Map(), c2: new Map(), c3: new Map(), vocab: new Map(), n: 0, nWords: 0 };
  const inc = (m, k) => m.set(k, (m.get(k) || 0) + 1);
  for (const w of norm(text).split(/[^ء-ی]+/).filter(Boolean)) {
    const s = '^^' + w + '$';
    for (let i = 2; i < s.length; i++) { inc(acc.c3, s.slice(i - 2, i + 1)); inc(acc.c2, s.slice(i - 1, i + 1)); inc(acc.c1, s[i]); acc.n++; }
    inc(acc.vocab, w); acc.nWords++;
  }
  return acc;
}
/** the stored model: counts only, the word list cut to words seen at least minWord times */
function pack(acc, minWord) {
  const o = (m) => Object.fromEntries(m);
  return { c1: o(acc.c1), c2: o(acc.c2), c3: o(acc.c3), vocab: o([...acc.vocab].filter(([, v]) => v >= minWord)), n: acc.n, nWords: acc.nWords };
}

function writeJs(json) {
  const head = '/**\n * The Persian language model (generated by tools/build-lm.js from tools/lm/lm.json — do not edit): letter n-gram and\n' +
    ' * word counts, for OCR\'s post-correction (3.4). Loaded only when needed, never at startup; a script, so it loads\n' +
    ' * from file:// too. Built from Kelk\'s own text and the Leipzig Corpora Collection\'s Iranian Persian corpora (CC BY:\n' +
    ' * D. Goldhahn, T. Eckart, U. Quasthoff, Building Large Monolingual Dictionaries at the Leipzig Corpora Collection:\n' +
    ' * From 100 to 200 Languages, LREC 2012; see THIRD-PARTY-NOTICES.md). Counts only: no sentence of the corpora.\n */\n';
  const body = '(function (global) {\n    \'use strict\';\n    const LM = ' + json.trim() + ';\n' +
    '    const PdfImporter = global.PdfImporter || (typeof require === \'function\' ? require(\'../PdfImporter.js\') : null);\n' +
    '    if (PdfImporter) PdfImporter._lmFa = LM;\n' +
    '    if (typeof module !== \'undefined\' && module.exports) module.exports = LM;\n' +
    '})(typeof window !== \'undefined\' ? window : globalThis);\n';
  fs.writeFileSync(JS_OUT, head + body);
  console.log(path.relative(root, JS_OUT) + ': ' + fs.statSync(JS_OUT).size + ' bytes');
}

if (process.argv.includes('--js')) {
  writeJs(fs.readFileSync(JSON_OUT, 'utf8'));
} else {
  const sources = (process.env.LM_SOURCES || '').split(',').filter(Boolean);
  if (sources.length !== 2) {
    console.error('LM_SOURCES must name the two Leipzig sentence files (web-public 2019 100K, wikipedia 2021 100K), comma-separated');
    process.exit(1);
  }
  let acc;
  const kelk = fs.readFileSync(path.join(root, 'tools', 'lm', 'kelk-text.txt'), 'utf8');
  for (let r = 0; r < KELK_WEIGHT; r++) acc = count(kelk, acc);
  for (const f of sources) {
    let ls = fs.readFileSync(f, 'utf8').split('\n');
    if (/web-public/.test(f)) ls = ls.filter((_, i) => i % HOLD !== 0);
    acc = count(ls.map((l) => l.slice(l.indexOf('\t') + 1)).join('\n'), acc);
  }
  fs.writeFileSync(JSON_OUT, JSON.stringify(pack(acc, MIN_WORD)));
  console.log(path.relative(root, JSON_OUT) + ': ' + fs.statSync(JSON_OUT).size + ' bytes, vocabulary ' + Object.keys(pack(acc, MIN_WORD).vocab).length);
  writeJs(fs.readFileSync(JSON_OUT, 'utf8'));
}
